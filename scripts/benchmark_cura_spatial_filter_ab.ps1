param(
    [string] $SpatialRoot = "",
    [int] $SliceTimeoutSeconds = 600
)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($SpatialRoot)) {
    $SpatialRoot = (Get-Content -LiteralPath (Join-Path $RepoRoot 'build\verification\cura-spatial-filter-current.txt') -Raw).Trim()
}

$ReleaseRoot = (Resolve-Path (Join-Path $RepoRoot 'build-vulkan\src\Release')).Path
$Executable = Join-Path $ReleaseRoot 'magpie-slicer.exe'
$LiveDll = Join-Path $ReleaseRoot 'MagpieSlicer.dll'
$PreviousDll = (Resolve-Path (Join-Path $SpatialRoot 'MagpieSlicer.previous.dll')).Path
$CurrentDll = Join-Path $SpatialRoot 'MagpieSlicer.current.dll'
$OutputRoot = Join-Path $SpatialRoot ('bunny-ab-' + (Get-Date -Format 'yyyyMMdd-HHmmss'))
$Machine = (Resolve-Path (Join-Path $RepoRoot 'build\verification\cura-bunny-support-top\20260723-173708\machine.json')).Path
$ProcessConfig = (Resolve-Path (Join-Path $RepoRoot 'build\verification\support-performance-20260806-141527\cura\process.json')).Path
$Model = (Resolve-Path (Join-Path $RepoRoot 'resources\handy_models\Stanford_Bunny.drc')).Path
$HistoricalGcode = (Resolve-Path (Join-Path $RepoRoot 'build\verification\support-performance-20260806-141527\cura\plate_1.gcode')).Path
Copy-Item -LiteralPath $LiveDll -Destination $CurrentDll -Force
New-Item -ItemType Directory -Force $OutputRoot | Out-Null

function Normalize-Line([string] $Line) {
    if ($Line -match '^; generated by OrcaSlicer .* on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}$') {
        return '; generated by OrcaSlicer <normalized>'
    }
    return $Line -replace '(; (?:stop )?printing object .* id:)\d+( copy \d+)', '$1<ID>$2'
}

function Get-CanonicalHash([string] $Path) {
    $Temporary = [IO.Path]::GetTempFileName()
    try {
        $Writer = [IO.StreamWriter]::new($Temporary, $false, [Text.UTF8Encoding]::new($false))
        try { foreach ($Line in [IO.File]::ReadLines($Path)) { $Writer.WriteLine((Normalize-Line $Line)) } }
        finally { $Writer.Dispose() }
        return (Get-FileHash -LiteralPath $Temporary -Algorithm SHA256).Hash
    } finally {
        Remove-Item -LiteralPath $Temporary -Force -ErrorAction SilentlyContinue
    }
}

function Wait-Gcode([Diagnostics.Process] $Process, [string] $Path, [int] $TimeoutSeconds) {
    $Deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSeconds)
    $LastLength = -1L
    $Stable = 0
    while ([DateTime]::UtcNow -lt $Deadline) {
        if (Test-Path -LiteralPath $Path) {
            $Length = (Get-Item -LiteralPath $Path).Length
            if ($Length -gt 0 -and $Length -eq $LastLength) { ++$Stable } else { $Stable = 0; $LastLength = $Length }
            if ($Stable -ge 3 -and (Get-Content -LiteralPath $Path -Tail 12) -match 'CONFIG_BLOCK_END') {
                if (-not $Process.HasExited -and -not $Process.WaitForExit(5000)) { Stop-Process -Id $Process.Id -Force }
                return Get-Item -LiteralPath $Path
            }
        }
        $Process.Refresh()
        if ($Process.HasExited -and -not (Test-Path -LiteralPath $Path)) { throw "Slice exited without G-code: $($Process.Id)" }
        Start-Sleep -Milliseconds 500
    }
    if (-not $Process.HasExited) { Stop-Process -Id $Process.Id -Force }
    throw "Slice timeout: $Path"
}

function Get-Median([double[]] $Values) {
    $Sorted = @($Values | Sort-Object)
    $Middle = [int]($Sorted.Count / 2)
    if (($Sorted.Count % 2) -eq 1) { return $Sorted[$Middle] }
    return ($Sorted[$Middle - 1] + $Sorted[$Middle]) / 2.0
}

$Sequence = @('previous', 'current', 'current', 'previous', 'previous', 'current', 'current', 'previous')
$Results = [Collections.Generic.List[object]]::new()
$ExpectedHash = Get-CanonicalHash $HistoricalGcode
try {
    for ($Index = 0; $Index -lt $Sequence.Count; ++$Index) {
        $Variant = $Sequence[$Index]
        $Dll = if ($Variant -eq 'previous') { $PreviousDll } else { $CurrentDll }
        Copy-Item -LiteralPath $Dll -Destination $LiveDll -Force

        $RunRoot = Join-Path $OutputRoot ('{0:D2}-{1}' -f ($Index + 1), $Variant)
        New-Item -ItemType Directory -Force $RunRoot | Out-Null
        $GcodePath = Join-Path $RunRoot 'plate_1.gcode'
        $Arguments = @('--slice', '0', '--debug', '1', '--load-settings', $Machine, '--load-settings', $ProcessConfig, '--outputdir', $RunRoot, $Model)
        $Watch = [Diagnostics.Stopwatch]::StartNew()
        $Process = Start-Process -FilePath $Executable -ArgumentList $Arguments -WorkingDirectory $ReleaseRoot `
            -RedirectStandardOutput (Join-Path $RunRoot 'stdout.log') `
            -RedirectStandardError (Join-Path $RunRoot 'stderr.log') -PassThru
        $Gcode = Wait-Gcode $Process $GcodePath $SliceTimeoutSeconds
        $Watch.Stop()
        $Hash = Get-CanonicalHash $Gcode.FullName
        if ($Hash -ne $ExpectedHash) { throw "Output mismatch for $Variant run $($Index + 1)" }
        $Results.Add([pscustomobject]@{ Order = $Index + 1; Variant = $Variant; Seconds = $Watch.Elapsed.TotalSeconds; Bytes = $Gcode.Length })
        Write-Output ('RUN order={0} variant={1} seconds={2:N3}' -f ($Index + 1), $Variant, $Watch.Elapsed.TotalSeconds)
    }
} finally {
    if (Get-Process -Name 'magpie-slicer' -ErrorAction SilentlyContinue) {
        Get-Process -Name 'magpie-slicer' | Stop-Process -Force
    }
    Copy-Item -LiteralPath $CurrentDll -Destination $LiveDll -Force
}

$PreviousTimes = @($Results | Where-Object Variant -eq 'previous' | Select-Object -ExpandProperty Seconds)
$CurrentTimes = @($Results | Where-Object Variant -eq 'current' | Select-Object -ExpandProperty Seconds)
$PreviousMedian = Get-Median $PreviousTimes
$CurrentMedian = Get-Median $CurrentTimes
$Summary = [pscustomobject]@{
    PreviousMedianSeconds = $PreviousMedian
    CurrentMedianSeconds = $CurrentMedian
    DeltaRatio = ($CurrentMedian / $PreviousMedian) - 1.0
    PreviousDllHash = (Get-FileHash -LiteralPath $PreviousDll -Algorithm SHA256).Hash
    CurrentDllHash = (Get-FileHash -LiteralPath $CurrentDll -Algorithm SHA256).Hash
    ActiveDllHash = (Get-FileHash -LiteralPath $LiveDll -Algorithm SHA256).Hash
    CanonicalGcodeHash = $ExpectedHash
    Runs = $Results
}
$SummaryPath = Join-Path $OutputRoot 'summary.json'
$Summary | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $SummaryPath -Encoding utf8
$Summary | ConvertTo-Json -Depth 5
Write-Output "SUMMARY=$SummaryPath"
