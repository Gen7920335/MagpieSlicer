#!/usr/bin/env python3
"""Feature-off golden corpus for Magpie Slicer.

Magpie's first contract is that a build with every Magpie module off produces the
same G-code as vanilla OrcaSlicer built from the same upstream commit. This tool
slices the corpus in corpus.json with one CLI binary, normalizes the lines that
legitimately differ between two builds (generator name and timestamp, per-process
object ids, optionally named config keys), and records a SHA-256 per case.

    golden.py slice --cli <orca-or-magpie-cli> --out <dir> [--external-models <dir>]
    golden.py compare <dir-a> <dir-b>
    golden.py determinism --cli <cli> --out <dir>
    golden.py mods --cli <magpie-cli> --vanilla-cli <orca-cli> --datadir <dir> --out <dir>

`slice` writes <dir>/manifest.json and <dir>/<case>/normalized.gcode.
`compare` exits 1 when any case differs or is missing on one side, and prints the
first differing normalized line of each such case.
`determinism` slices twice into <dir>/run1 and <dir>/run2 and compares them. Run it
before trusting a comparison: a case that differs between two runs of the same
binary cannot gate anything until the nondeterministic lines are understood.
`mods` checks that a mod which is on but resolves to the same settings changes nothing:
mods/noop.json (on, every setting unchanged) against vanilla, and mods/set.json (rules
that change values) against vanilla with the same values set in the process preset
(mods/set.overrides.json). The second comparison drops different_settings_to_system,
the list of keys the user changed, which a mod rule rightly does not add to.

On Windows pass the console binary that accepts CLI arguments (for example
build/src/Release/magpie-slicer.exe, or orca-slicer.exe for the vanilla build).
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
ROOT = os.path.dirname(ROOT)

# Lines that differ between two correct builds. Each entry is (pattern, replacement).
NORMALIZERS = [
    # Producer name, version and wall-clock time of the run.
    (re.compile(r'^; generated by .*$'), '; generated by <normalized>'),
    # Object ids come from a process-wide counter, so they depend on what was loaded before.
    (re.compile(r'(; (?:printing|stop printing) object .*?) id:\d+'), r'\1 id:<n>'),
]


def load_corpus(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def normalize(lines, ignore_keys):
    key_patterns = [re.compile(r'^; ' + re.escape(k) + r' = ') for k in ignore_keys]
    out = []
    for line in lines:
        if any(p.match(line) for p in key_patterns):
            continue
        for pattern, repl in NORMALIZERS:
            line = pattern.sub(repl, line)
        out.append(line)
    return out


def write_preset(src, overrides, dst, user_dir=None, kind=None):
    with open(os.path.join(HERE, src), encoding='utf-8') as f:
        preset = json.load(f)
    preset.update(overrides or {})
    if user_dir:
        # The nightly CLI resolves a "from": "User" preset only when the file is one the
        # preset bundle loaded from <datadir>/user/default/<kind>/, and the bundle skips a
        # user preset without a "version" key.
        preset.setdefault('version', '2.4.0.0')
        kind_dir = os.path.join(user_dir, kind)
        os.makedirs(kind_dir, exist_ok=True)
        dst = os.path.join(kind_dir, preset['name'] + '.json')
    with open(dst, 'w', encoding='utf-8') as f:
        json.dump(preset, f, indent=4)
    return dst


def resolve_model(model, external_dir):
    if model.startswith('external:'):
        if not external_dir:
            return None
        path = os.path.join(external_dir, model[len('external:'):])
    else:
        path = os.path.join(ROOT, model)
    return path if os.path.isfile(path) else None


def slice_corpus(cli, out, corpus_path, external_dir, only, ignore_keys, timeout_s, datadir=None):
    corpus = load_corpus(corpus_path)
    os.makedirs(out, exist_ok=True)
    manifest = {'cli': os.path.abspath(cli), 'corpus': os.path.relpath(corpus_path, ROOT), 'cases': {}}
    failed = False
    for case in corpus['cases']:
        name = case['name']
        if only and name not in only:
            continue
        model = resolve_model(case['model'], external_dir)
        if model is None:
            status = 'skipped' if case.get('optional') else 'missing-model'
            failed |= status == 'missing-model'
            manifest['cases'][name] = {'status': status}
            print(f'{name}: {status}')
            continue
        case_dir = os.path.join(out, name)
        shutil.rmtree(case_dir, ignore_errors=True)
        os.makedirs(case_dir)
        printer = corpus['printers'][case['printer']]
        user_dir = os.path.join(datadir, 'user', 'default') if datadir else None
        machine = write_preset(printer['machine'], case.get('machine'), os.path.join(case_dir, 'machine.json'),
                               user_dir, 'machine')
        process = write_preset(printer['process'], case.get('process'), os.path.join(case_dir, 'process.json'),
                               user_dir, 'process')
        filaments = [write_preset(f, case.get('filament'), os.path.join(case_dir, f'filament_{i}.json'),
                                  user_dir, 'filament')
                     for i, f in enumerate(printer['filaments'])]
        if user_dir:
            for i, src in enumerate([machine, process] + filaments):
                shutil.copyfile(src, os.path.join(case_dir, os.path.basename(src)))
        gcode_dir = os.path.join(case_dir, 'out')
        os.makedirs(gcode_dir)
        cmd = [cli]
        if datadir:
            cmd += ['--datadir', datadir]
        if printer.get('bed_type'):
            cmd += ['--curr-bed-type', printer['bed_type']]
        cmd += ['--slice', '0',
               '--load-settings', f'{machine};{process}',
               '--load-filaments', ';'.join(filaments),
               '--outputdir', gcode_dir]
        # Extra CLI options for the case, such as --filament_colour for multi-filament cases.
        # A relative path among the extra arguments (a second model) is the repository's, like `model`.
        cli_args = [os.path.join(ROOT, a) if not os.path.isabs(a) and os.path.isfile(os.path.join(ROOT, a)) else a
                    for a in case.get('cli_args', [])]
        cmd += cli_args + [model]
        started = time.monotonic()
        try:
            proc = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace',
                                  timeout=timeout_s)
            code = proc.returncode
            with open(os.path.join(case_dir, 'cli.log'), 'w', encoding='utf-8') as f:
                f.write(' '.join(cmd) + '\n\n' + proc.stdout + '\n' + proc.stderr)
            # A mod that fails to load is only logged, and the slice then runs without it. A
            # comparison that silently lost its mod would pass for the wrong reason.
            if code == 0 and 'Mod not loaded' in proc.stdout + proc.stderr:
                code = 'mod-not-loaded'
        except subprocess.TimeoutExpired:
            code = 'timeout'
        seconds = round(time.monotonic() - started, 2)
        gcodes = sorted(p for p in os.listdir(gcode_dir) if p.endswith('.gcode'))
        if code != 0 or not gcodes:
            failed = True
            manifest['cases'][name] = {'status': 'slice-failed', 'exit': code, 'seconds': seconds}
            print(f'{name}: slice failed (exit {code}), see {case_dir}/cli.log')
            continue
        lines = []
        for g in gcodes:
            with open(os.path.join(gcode_dir, g), encoding='utf-8', errors='surrogateescape') as f:
                lines.append(f'; ==== {g}\n')
                lines.extend(f.readlines())
        norm = normalize(lines, ignore_keys)
        norm_path = os.path.join(case_dir, 'normalized.gcode')
        with open(norm_path, 'w', encoding='utf-8', errors='surrogateescape') as f:
            f.writelines(norm)
        digest = hashlib.sha256(''.join(norm).encode('utf-8', 'surrogateescape')).hexdigest()
        manifest['cases'][name] = {'status': 'ok', 'sha256': digest, 'lines': len(norm), 'seconds': seconds}
        print(f'{name}: {digest[:16]} ({len(norm)} lines, {seconds}s)')
    with open(os.path.join(out, 'manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=2)
    return 1 if failed else 0


def first_difference(path_a, path_b):
    with open(path_a, encoding='utf-8', errors='surrogateescape') as fa, \
         open(path_b, encoding='utf-8', errors='surrogateescape') as fb:
        for n, (la, lb) in enumerate(zip(fa, fb), 1):
            if la != lb:
                return n, la.rstrip('\n'), lb.rstrip('\n')
    return None, '<length differs>', ''


def compare(dir_a, dir_b):
    with open(os.path.join(dir_a, 'manifest.json'), encoding='utf-8') as f:
        a = json.load(f)['cases']
    with open(os.path.join(dir_b, 'manifest.json'), encoding='utf-8') as f:
        b = json.load(f)['cases']
    bad = 0
    for name in sorted(set(a) | set(b)):
        ca, cb = a.get(name, {}), b.get(name, {})
        if ca.get('status') == 'skipped' and cb.get('status') == 'skipped':
            print(f'SKIP  {name}')
            continue
        if ca.get('status') != 'ok' or cb.get('status') != 'ok':
            bad += 1
            print(f'FAIL  {name}: {ca.get("status", "absent")} / {cb.get("status", "absent")}')
            continue
        if ca['sha256'] == cb['sha256']:
            print(f'SAME  {name}')
            continue
        bad += 1
        line, la, lb = first_difference(os.path.join(dir_a, name, 'normalized.gcode'),
                                        os.path.join(dir_b, name, 'normalized.gcode'))
        print(f'DIFF  {name} at normalized line {line}\n      a: {la}\n      b: {lb}')
    print(f'{bad} case(s) differ or failed' if bad else 'all cases identical')
    return 1 if bad else 0


def mods_equivalence(args):
    """Mods on, settings equal: Magpie must match vanilla. Returns the number of failed comparisons."""
    out = os.path.abspath(args.out)
    datadir = os.path.abspath(args.datadir)
    failed = 0
    with open(os.path.join(HERE, 'mods', 'set.overrides.json'), encoding='utf-8') as f:
        overrides = json.load(f)['process']
    corpus = load_corpus(args.corpus)
    for case in corpus['cases']:
        clash = set(overrides) & set(case.get('process', {}))
        if clash:
            raise SystemExit(f'case {case["name"]} already sets {sorted(clash)}; pick other keys in mods/set.overrides.json')
        case.setdefault('process', {}).update(overrides)
    set_corpus = os.path.join(out, 'corpus_set.json')
    os.makedirs(out, exist_ok=True)
    with open(set_corpus, 'w', encoding='utf-8') as f:
        json.dump(corpus, f, indent=2)

    def datadir_with(mod):
        # A copy of the data directory with one mod, so the vanilla data directory stays mod-free.
        dst = os.path.join(out, 'datadir_' + mod)
        shutil.rmtree(dst, ignore_errors=True)
        shutil.copytree(datadir, dst, ignore=shutil.ignore_patterns('log', 'mods'))
        os.makedirs(os.path.join(dst, 'mods'))
        shutil.copyfile(os.path.join(HERE, 'mods', mod + '.json'), os.path.join(dst, 'mods', mod + '.json'))
        return dst

    only = set(args.cases.split(',')) if args.cases else None
    run = lambda cli, name, corpus_path, dd, ignore: slice_corpus(cli, os.path.join(out, name), corpus_path, args.external_models,
                                                                   only, ignore, args.timeout, dd)
    print('== noop mod against vanilla')
    run(args.vanilla_cli, 'vanilla', args.corpus, datadir, [])
    run(args.cli, 'magpie_noop', args.corpus, datadir_with('noop'), [])
    failed += compare(os.path.join(out, 'vanilla'), os.path.join(out, 'magpie_noop'))
    print('== value-setting mod against vanilla with the same values')
    ignore = ['different_settings_to_system']
    run(args.vanilla_cli, 'vanilla_set', set_corpus, datadir, ignore)
    run(args.cli, 'magpie_set', args.corpus, datadir_with('set'), ignore)
    failed += compare(os.path.join(out, 'vanilla_set'), os.path.join(out, 'magpie_set'))
    return 1 if failed else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    for name in ('slice', 'determinism'):
        p = sub.add_parser(name)
        p.add_argument('--cli', required=True)
        p.add_argument('--out', required=True)
        p.add_argument('--corpus', default=os.path.join(HERE, 'corpus.json'))
        p.add_argument('--external-models', help='directory holding models named external:<file> in the corpus')
        p.add_argument('--cases', help='comma-separated case names to run')
        p.add_argument('--ignore-key', action='append', default=[],
                       help='drop the "; <key> = ..." config line, for keys only one build writes')
        p.add_argument('--timeout', type=int, default=1800, help='per-case slicing timeout in seconds')
        p.add_argument('--datadir', help='CLI data directory; its system/ must hold the vendor profiles the presets '
                                         'inherit from. User presets are written to <datadir>/user/default/')
    m = sub.add_parser('mods')
    m.add_argument('--cli', required=True, help='the Magpie CLI')
    m.add_argument('--vanilla-cli', required=True, help='a vanilla OrcaSlicer CLI built from the same upstream commit')
    m.add_argument('--out', required=True)
    m.add_argument('--datadir', required=True, help='a mod-free data directory, as for slice')
    m.add_argument('--corpus', default=os.path.join(HERE, 'corpus.json'))
    m.add_argument('--external-models')
    m.add_argument('--cases')
    m.add_argument('--timeout', type=int, default=1800)
    c = sub.add_parser('compare')
    c.add_argument('a')
    c.add_argument('b')
    args = ap.parse_args()
    if args.cmd == 'compare':
        return compare(args.a, args.b)
    if args.cmd == 'mods':
        return mods_equivalence(args)
    only = set(args.cases.split(',')) if args.cases else None
    if args.cmd == 'slice':
        return slice_corpus(args.cli, args.out, args.corpus, args.external_models, only, args.ignore_key, args.timeout,
                            os.path.abspath(args.datadir) if args.datadir else None)
    rc = 0
    for run in ('run1', 'run2'):
        rc |= slice_corpus(args.cli, os.path.join(args.out, run), args.corpus, args.external_models,
                           only, args.ignore_key, args.timeout,
                           os.path.abspath(args.datadir) if args.datadir else None)
    return compare(os.path.join(args.out, 'run1'), os.path.join(args.out, 'run2')) or rc


if __name__ == '__main__':
    sys.exit(main())
